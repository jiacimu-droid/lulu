    override fun plannedMinutesOverride(date: LocalDate): Int? = when {
        date < startDate -> null
        date <= LocalDate.of(2026, 8, 9) -> 240
        date <= LocalDate.of(2026, 8, 23) -> 270
        date <= LocalDate.of(2026, 9, 30) -> 300
        date <= LocalDate.of(2026, 11, 30) -> 330
        else -> 300
    }

    fun dynamicSchedulePrompt(
        date: LocalDate,
        presetPlan: DailyStudyPlan?,
        tasks: List<StudyTask>,
        currentTime: LocalTime,
    ): String = buildString {
        val formatter = DateTimeFormatter.ofPattern("HH:mm")
        val unfinished = tasks.filterNot(StudyTask::done)
        appendLine("日期：$date；当前时间：${currentTime.format(formatter)}。")
        appendLine("用户自己决定今天是否休息以及具体学习顺序。不要假设周日或任何固定星期必须休息。")
        appendLine("今日短提醒：${presetPlan?.tasks.orEmpty().joinToString("；") { it.title }}")
        appendLine("当前未完成待办：")
        if (unfinished.isEmpty()) {
            appendLine("- 没有明确待办；只给最多4条短提醒。")
        } else {
            unfinished.take(8).forEach { task -> appendLine("- ${task.title}") }
        }
        appendLine("从当前时间以后安排最多4个短时间块。手动待办优先；超出今天容量的内容留在周任务池，不惩罚式补课。")
        appendLine("必须至少保留一次离桌轻活动或吃饭休息；最后一块只做有效分钟和卡点记录。")
        appendLine("只输出：HH:mm-HH:mm｜标题｜一句具体建议。")
    }

